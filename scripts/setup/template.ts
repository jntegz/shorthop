// The Wrangler config, rendered from one description. The setup wizard writes
// wrangler.jsonc with it; wrangler.example.jsonc is the same template with
// placeholder values (a test keeps the two in step).

import { existsSync, readFileSync } from "node:fs";
import { parse, printParseErrorCode, type ParseError } from "jsonc-parser";
import { CHECKS_CRON, DIGEST_CRON, ROLLUP_CRON } from "../../src/shared/schedule";
import { DIGEST_PROVIDERS as PROVIDERS, type DigestProvider } from "../../src/shared/types";

export const CONFIG_FILE = "wrangler.jsonc";
export const EXAMPLE_FILE = "wrangler.example.jsonc";

export type Provider = DigestProvider;
export type AuthMode = "access+password" | "password";
export type Plan = "free" | "paid";
export type TokenScope = "create" | "full";

export interface SetupConfig {
  workerName: string;
  /** Empty in the example: Wrangler then asks or uses the only account. */
  accountId: string;
  /** Primary first. */
  shortDomains: string[];
  /** Empty means the primary short domain hosts the admin. */
  adminHost: string;
  fallbackUrl: string;
  authMode: AuthMode;
  accessTeamDomain: string;
  accessAud: string;
  adminEmail: string;
  /** Null until the namespace exists (the example has none). */
  kvId: string | null;
  d1Name: string;
  d1Id: string | null;
  aeDataset: string;
  plan: Plan;
  /** What API_TOKEN may do; only "full" lets it change and delete. */
  tokenScope: TokenScope;
  digestProvider: Provider;
  digestFrom: string;
  digestTo: string;
  mailgunDomain: string;
  mailgunRegion: "us" | "eu";
  /** Custom email API only, optional: auth header and JSON body template. Empty uses the defaults. */
  customAuth: string;
  customBody: string;
}

