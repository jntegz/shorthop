/** Every hostname the Worker needs a custom domain for. */
export function routeHosts(c: SetupConfig): string[] {
  return [...new Set([...c.shortDomains, ...(c.adminHost ? [c.adminHost] : [])])];
}

const j = (v: unknown) => JSON.stringify(v);

export function renderConfig(c: SetupConfig): string {
  const routes = routeHosts(c)
    .map((h) => `    { "pattern": ${j(h)}, "custom_domain": true }`)
    .join(",\n");
  const kv = c.kvId ? `{ "binding": "LINKS", "id": ${j(c.kvId)} }` : `{ "binding": "LINKS" }`;
  const d1Id = c.d1Id ? `\n      "database_id": ${j(c.d1Id)},` : "";
  const sendEmail =
    c.digestProvider === "cloudflare"
      ? `
  "send_email": [
    {
      "name": "DIGEST",
      // Cloudflare Email Service can only ever send the digest to this address.
      "destination_address": ${j(c.digestTo)},
      "allowed_sender_addresses": [${j(c.digestFrom)}]
    }
  ],
`
      : "";
  const mailgun =
    c.digestProvider === "mailgun"
      ? `
    "DIGEST_MAILGUN_DOMAIN": ${j(c.mailgunDomain)},
    "DIGEST_MAILGUN_REGION": ${j(c.mailgunRegion)},`
      : "";
  const custom =
    (c.customAuth ? `\n    "DIGEST_CUSTOM_AUTH": ${j(c.customAuth)},` : "") + (c.customBody ? `\n    "DIGEST_CUSTOM_BODY": ${j(c.customBody)},` : "");
  const account = c.accountId ? `\n  "account_id": ${j(c.accountId)},` : "";

  return `// Generated by \`npm run setup\` (scripts/setup/template.ts). Re-run the setup to
// change it, or edit it by hand: the setup reads it back. Secrets are never here.
{
  "$schema": "node_modules/wrangler/config-schema.json",
  "name": ${j(c.workerName)},${account}
  "main": "src/worker/index.ts",
  "compatibility_date": "2026-10-19",
  "compatibility_flags": ["nodejs_compat"],
  "workers_dev": false,
  "preview_urls": false,
  // One custom domain per short domain, plus ADMIN_HOST. Each must be in a zone
  // in this Cloudflare account, with no DNS record of its own on the hostname.
  "routes": [
${routes}
  ],

  "assets": {
    "binding": "ASSETS",
    // No SPA fallback and no HTML auto-handling: every unknown path must reach
    // the Worker so it can be treated as a slug. Only exact files bypass it.
    "html_handling": "none",
    "not_found_handling": "none",
    // The admin shell goes through the Worker (auth check + CSP); its hashed
    // JS/CSS bundles are served straight from the asset store.
    "run_worker_first": ["/_admin/*", "!/_admin/assets/*"]
  },

  "kv_namespaces": [${kv}],
  "d1_databases": [
    {
      "binding": "DB",
      "database_name": ${j(c.d1Name)},${d1Id}
      "migrations_dir": "migrations"
    }
  ],
  "analytics_engine_datasets": [{ "binding": "CLICKS", "dataset": ${j(c.aeDataset)} }],
  "ratelimits": [
    // Failed API-token attempts per client IP.
    { "name": "AUTH_LIMITER", "namespace_id": "1001", "simple": { "limit": 10, "period": 60 } },
    // Admin password attempts per client network (a burst brake; the lockout
    // that counts is kept in D1).
    { "name": "LOGIN_LIMITER", "namespace_id": "1002", "simple": { "limit": 5, "period": 60 } }
  ],
${sendEmail}
  "triggers": {
    // Daily rollup at 01:15 UTC, weekly digest Mondays 07:00 UTC, destination
    // checks every 30 minutes (src/shared/schedule.ts).
    "crons": [${j(ROLLUP_CRON)}, ${j(DIGEST_CRON)}, ${j(CHECKS_CRON)}]
  },

  "vars": {
    // "access+password" (or empty): Cloudflare Access in front of the admin
    // password. "password": the password alone. Anything else locks the admin.
    "ADMIN_AUTH": ${j(c.authMode)},
    // Cloudflare Access team domain ("yourteam.cloudflareaccess.com") and the
    // application's AUD tag. With Access on, the admin fails closed while empty.
    "ACCESS_TEAM_DOMAIN": ${j(c.accessTeamDomain)},
    "ACCESS_AUD": ${j(c.accessAud)},
    // The only Access identity allowed into the admin, comma-separated for more.
    "ADMIN_EMAIL": ${j(c.adminEmail)},
    // Needed to query Analytics Engine over its SQL API (with CF_ANALYTICS_TOKEN).
    "CF_ACCOUNT_ID": ${j(c.accountId)},
    // Short domains, comma-separated, primary first. New links default to the
    // primary; it also hosts the admin and the API unless ADMIN_HOST is set.
    "SHORT_DOMAINS": ${j(c.shortDomains.join(","))},
    // Optional separate host for the admin and the API (no short links there).
    "ADMIN_HOST": ${j(c.adminHost)},
    // Where "/" goes, and clicks when the link store can't be read. Referrals from its host count as "site".
    "FALLBACK_URL": ${j(c.fallbackUrl)},
    "KV_CACHE_TTL": "60",
    // The Analytics Engine dataset above (letters, digits and _ only).
    "AE_DATASET": ${j(c.aeDataset)},
    // "free" or "paid": System status checks the password hash cost against it.
    "WORKERS_PLAN": ${j(c.plan)},
    // What the API token may do: "create" reads, creates links and imports new
    // ones; "full" also changes and deletes links and settings.
    "API_TOKEN_SCOPE": ${j(c.tokenScope)},
    // Digest and alert delivery: ${PROVIDERS.join(", ")}.
    // Settings → Weekly digest → Set up email overrides the provider and sender
    // without a deploy. API keys and URLs are secrets (docs/SETUP.md#email).
    "DIGEST_PROVIDER": ${j(c.digestProvider)},
    "DIGEST_FROM": ${j(c.digestFrom)},
    // The only recipient.
    "DIGEST_TO": ${j(c.digestTo)},${mailgun}${custom}
    // Set to "1" only in .dev.vars. Honored solely on localhost/127.0.0.1.
    "DEV_AUTH_BYPASS": ""
  },

  "secrets": {
    // Set by \`npm run setup\`. API_TOKEN: Bearer token for /api. VISITOR_SALT:
    // mixed into the visitor hash. ADMIN_PASSWORD_HASH: the admin password's PBKDF2
    // hash. SESSION_SECRET: signs admin sessions (rotate it to log out everywhere).
    // Optional: CF_ANALYTICS_TOKEN and the digest provider's keys.
    "required": ["API_TOKEN", "VISITOR_SALT", "ADMIN_PASSWORD_HASH", "SESSION_SECRET"]
  },

  "observability": {
    "enabled": true,
    "logs": { "enabled": true, "head_sampling_rate": 1 },
    "traces": { "enabled": true, "head_sampling_rate": 0.05 }
  }
}
`;
}

type Raw = Record<string, unknown>;
const obj = (v: unknown): Raw => (typeof v === "object" && v !== null && !Array.isArray(v) ? (v as Raw) : {});
const arr = (v: unknown): unknown[] => (Array.isArray(v) ? v : []);
const str = (v: unknown, fallback = ""): string => (typeof v === "string" ? v : fallback);

export function parseJsonc(text: string, file: string): Raw {
  const errors: ParseError[] = [];
  const data = parse(text, errors, { allowTrailingComma: true });
  if (errors.length) throw new Error(`${file}: ${printParseErrorCode(errors[0]!.error)} at offset ${errors[0]!.offset}`);
  return obj(data);
}

/** Reads a config written by renderConfig (or edited by hand) back into its description. */
export function configFromText(text: string, file = CONFIG_FILE): SetupConfig {
  const raw = parseJsonc(text, file);
  const vars = obj(raw.vars);
  const kv = obj(arr(raw.kv_namespaces).map(obj).find((k) => k.binding === "LINKS"));
  const d1 = obj(arr(raw.d1_databases).map(obj).find((d) => d.binding === "DB"));
  const ae = obj(arr(raw.analytics_engine_datasets).map(obj).find((d) => d.binding === "CLICKS"));
  const provider = str(vars.DIGEST_PROVIDER, "cloudflare").trim().toLowerCase();
  const auth = str(vars.ADMIN_AUTH);
  // Rewriting an unknown value as the default would silently unlock a deliberately locked admin.
  if (!["", "access+password", "password"].includes(auth)) throw new Error(`${file}: ADMIN_AUTH is "${auth}"; use "access+password" or "password".`);
  return {
    workerName: str(raw.name, EXAMPLE_CONFIG.workerName),
    accountId: str(raw.account_id) || str(vars.CF_ACCOUNT_ID),
    shortDomains: str(vars.SHORT_DOMAINS)
      .split(",")
      .map((d) => d.trim().toLowerCase())
      .filter(Boolean),
    adminHost: str(vars.ADMIN_HOST).trim().toLowerCase(),
    fallbackUrl: str(vars.FALLBACK_URL),
    authMode: auth === "password" ? "password" : "access+password",
    accessTeamDomain: str(vars.ACCESS_TEAM_DOMAIN),
    accessAud: str(vars.ACCESS_AUD),
    adminEmail: str(vars.ADMIN_EMAIL),
    kvId: str(kv.id) || null,
    d1Name: str(d1.database_name, EXAMPLE_CONFIG.d1Name),
    d1Id: str(d1.database_id) || null,
    aeDataset: str(vars.AE_DATASET) || str(ae.dataset, EXAMPLE_CONFIG.aeDataset),
    plan: str(vars.WORKERS_PLAN) === "paid" ? "paid" : "free",
    tokenScope: str(vars.API_TOKEN_SCOPE) === "full" ? "full" : "create",
    digestProvider: (PROVIDERS as readonly string[]).includes(provider) ? (provider as Provider) : "off",
    digestFrom: str(vars.DIGEST_FROM),
    digestTo: str(vars.DIGEST_TO),
    mailgunDomain: str(vars.DIGEST_MAILGUN_DOMAIN),
    mailgunRegion: str(vars.DIGEST_MAILGUN_REGION) === "eu" ? "eu" : "us",
    customAuth: str(vars.DIGEST_CUSTOM_AUTH),
    // A body written as a JSON object is kept, as a string.
    customBody: typeof vars.DIGEST_CUSTOM_BODY === "object" && vars.DIGEST_CUSTOM_BODY ? JSON.stringify(vars.DIGEST_CUSTOM_BODY) : str(vars.DIGEST_CUSTOM_BODY),
  };
}

/** wrangler.jsonc when the setup has written one, else the example (for local dev). */
export function localConfig(): { file: string; config: SetupConfig } {
  const file = existsSync(CONFIG_FILE) ? CONFIG_FILE : EXAMPLE_FILE;
  return { file, config: configFromText(readFileSync(file, "utf8"), file) };
}

/** Reserved names that can never be a real deployment's domain. */
export function isPlaceholderHost(host: string): boolean {
  return /\.(example|invalid|test|localhost)$/.test(host);
}

/** Why this config can't be deployed as it is, or an empty list. */
export function deployProblems(c: SetupConfig): string[] {
  const problems: string[] = [];
  if (!c.accountId) problems.push("account_id is missing.");
  if (!c.kvId) problems.push("The LINKS KV namespace has no id (Wrangler would create a new one).");
  if (!c.d1Id) problems.push("The DB database has no database_id (Wrangler would create a new one).");
  if (!c.shortDomains.length) problems.push("SHORT_DOMAINS is empty.");
  const placeholder = routeHosts(c).find(isPlaceholderHost);
  if (placeholder) problems.push(`${placeholder} is a placeholder domain.`);
  return problems;
}
